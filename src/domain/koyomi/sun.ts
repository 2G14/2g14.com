function vsop(series: readonly (readonly VsopTerm[])[], tau: number): number {
  return (
    series.reduce(
      (total, terms, power) =>
        total + terms.reduce((sum, [a, b, c]) => sum + a * Math.cos(b + c * tau), 0) * tau ** power,
      0,
    ) / 1e8
  );
}

/**
 * 太陽の視黄経（度）。VSOP87 の主要項から地心黄経を求め、章動と光行差を補正する。
 * 誤差は 1 秒角程度（時刻にして 30 秒弱）。
 */
function sunApparentLongitude(jde: number): number {
  const t = (jde - 2451545) / 36525;
  const tau = t / 10;
  const geometric = vsop(EARTH_L, tau) / RAD + 180 - 0.09033 / 3600;
  const radius = vsop(EARTH_R, tau);

  // 章動の主要項（秒角）。Ω は月の昇交点黄経、l と lp は太陽と月の平均黄経
  const omega = 125.04452 - 1934.136261 * t;
  const l = 280.4665 + 36000.7698 * t;
  const lp = 218.3165 + 481267.8813 * t;
  const nutation =
    -17.2 * sinDeg(omega) - 1.32 * sinDeg(2 * l) - 0.23 * sinDeg(2 * lp) + 0.21 * sinDeg(2 * omega);
  const aberration = -20.4898 / radius;

  return normalizeDegrees(geometric + (nutation + aberration) / 3600);
}

const TROPICAL_YEAR_DAYS = 365.2422;

/**
 * 太陽の視黄経が longitude 度になる時刻（力学時のユリウス日）。
 * nearJde の前後半年以内にある 1 回を、ニュートン法で求める。
 */
export function solarLongitudeTime(longitude: number, nearJde: number): number {
  let jde = nearJde;
  for (let i = 0; i < 20; i++) {
    // 差を -180〜180 度に収め、近い方の通過時刻へ寄せる
    const diff = normalizeDegrees(longitude - sunApparentLongitude(jde) + 180) - 180;
    jde += (diff * TROPICAL_YEAR_DAYS) / 360;
    if (Math.abs(diff) < 1e-7) break;
  }
  return jde;
}
